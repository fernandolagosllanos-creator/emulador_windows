import Foundation

/// Traduce los códigos de tecla del Mac (kVK_*, posición física) a scancodes XT de PC.
/// Así Windows aplica su propia distribución de teclado (p. ej. español) a la tecla pulsada.
public enum KeyMap {
    /// Scancode XT para un código de tecla del Mac, o nil si no tiene equivalente.
    /// Los teclados ISO del Mac (como el español) intercambian los códigos de la tecla a la izquierda
    /// del 1 y la de la derecha del Mayúsculas izquierdo respecto a un teclado de PC.
    public static func scancode(macKeyCode: UInt16, isISOKeyboard: Bool = false) -> UInt32? {
        if isISOKeyboard {
            if macKeyCode == 0x0A { return 0x29 } // tecla a la izquierda del 1 (º en español)
            if macKeyCode == 0x32 { return 0x56 } // tecla junto al Mayúsculas izquierdo (<)
        }
        return table[macKeyCode]
    }

    /// Las teclas extendidas (prefijo 0xE0) se escriben 0x80 | código, como espera QEMU.
    static let table: [UInt16: UInt32] = [
        // Letras
        0x00: 0x1E, 0x01: 0x1F, 0x02: 0x20, 0x03: 0x21, 0x04: 0x23, 0x05: 0x22, 0x06: 0x2C, 0x07: 0x2D,
        0x08: 0x2E, 0x09: 0x2F, 0x0B: 0x30, 0x0C: 0x10, 0x0D: 0x11, 0x0E: 0x12, 0x0F: 0x13, 0x10: 0x15,
        0x11: 0x14, 0x1F: 0x18, 0x20: 0x16, 0x22: 0x17, 0x23: 0x19, 0x25: 0x26, 0x26: 0x24, 0x28: 0x25,
        0x2D: 0x31, 0x2E: 0x32,
        // Números y símbolos
        0x12: 0x02, 0x13: 0x03, 0x14: 0x04, 0x15: 0x05, 0x16: 0x07, 0x17: 0x06, 0x18: 0x0D, 0x19: 0x0A,
        0x1A: 0x08, 0x1B: 0x0C, 0x1C: 0x09, 0x1D: 0x0B, 0x1E: 0x1B, 0x21: 0x1A, 0x27: 0x28, 0x29: 0x27,
        0x2A: 0x2B, 0x2B: 0x33, 0x2C: 0x35, 0x2F: 0x34, 0x32: 0x29, 0x0A: 0x56,
        // Edición
        0x24: 0x1C, 0x30: 0x0F, 0x31: 0x39, 0x33: 0x0E, 0x35: 0x01, 0x75: 0xD3, 0x72: 0xD2,
        // Modificadores: Comando = tecla Windows, Opción = Alt, Opción derecha = AltGr
        0x37: 0xDB, 0x36: 0xDC, 0x38: 0x2A, 0x3C: 0x36, 0x39: 0x3A, 0x3A: 0x38, 0x3D: 0xB8,
        0x3B: 0x1D, 0x3E: 0x9D,
        // Navegación
        0x73: 0xC7, 0x77: 0xCF, 0x74: 0xC9, 0x79: 0xD1, 0x7B: 0xCB, 0x7C: 0xCD, 0x7D: 0xD0, 0x7E: 0xC8,
        // Funciones (F13 = Impr Pant)
        0x7A: 0x3B, 0x78: 0x3C, 0x63: 0x3D, 0x76: 0x3E, 0x60: 0x3F, 0x61: 0x40, 0x62: 0x41, 0x64: 0x42,
        0x65: 0x43, 0x6D: 0x44, 0x67: 0x57, 0x6F: 0x58, 0x69: 0xB7,
        // Teclado numérico
        0x52: 0x52, 0x53: 0x4F, 0x54: 0x50, 0x55: 0x51, 0x56: 0x4B, 0x57: 0x4C, 0x58: 0x4D, 0x59: 0x47,
        0x5B: 0x48, 0x5C: 0x49, 0x41: 0x53, 0x43: 0x37, 0x45: 0x4E, 0x4E: 0x4A, 0x4B: 0xB5, 0x4C: 0x9C,
        0x47: 0x45,
    ]
}
